/**
 * 繁体转简体（逐字替换，幂等）。
 *
 * 非中文字符（标点、数字、英文、emoji）原样保留；
 * 简体字不在映射表内，重复调用结果不变。
 * @param {string} text 待转换文本
 * @returns {string} 简体文本（输入非字符串时按 '' 处理）
 */
export function toSimplified(text) {
  const source = typeof text === 'string' ? text : text === null || text === undefined ? '' : String(text);
  if (!source) return '';
  let output = '';
  // for...of 按码点遍历，emoji 等代理对不会被拆开
  for (const char of source) {
    output += T2S[char] ?? char;
  }
  return output;
}

export default toSimplified;
